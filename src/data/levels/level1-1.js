/**
 * 1-1 隐性教学关（Mario 101）。
 *
 * 本关按《调研报告》二·1~4 的方法论"后置设计"：机制全部做完后最后编写。
 * 每个物件都有注释标注教学意图——零文字，全部靠布局教学。
 */

import { LevelBuilder } from '../levelBuilder.js';

const W = 176;
const H = 15;
const GY = 13; // 地表行

const b = new LevelBuilder(W, H);

/* —— 起步安全区（挑战单元 0：什么都没有，先learn走路）—— */
b.ground(0, 33, GY);
b.block(2, 12, '"'); // 灌木装饰

/* 教学 1：第一个敌人 = 栗宝宝（专为新手发明：一脚踩扁，单步交互）。
   它从右边走来，玩家要么跳过要么踩——两种解都会立刻得到正反馈。 */
b.enemy('goomba', 14, 12);

/* 教学 2：问号块三连——第一次"向上撞"的奖励。
   中间是道具块：蘑菇会弹出并向前走，玩家追逐中学会"道具是好东西"。 */
b.block(16, 9, '?');
b.block(17, 9, 'M');
b.block(18, 9, '?');

/* 教学 3：SMB3 招牌斜坡——上坡不需要跳，走上去就行（物理服从直觉）。 */
b.slopeUp(24, 12, 3);
b.ground(27, 30, 10);       // 坡顶平台
b.coins(27, 30, 8);         // 坡顶金币=爬坡的甜头
b.slopeDown(31, 10, 3);
b.ground(34, 35, GY);

/* —— 教学 4：双坑跳跃教学（《调研报告》二·4 逐条复刻）—— */
/* 坑 A：有底，掉下去死不了，可以在里面练习跳出来 */
b.ground(36, 47, GY);
b.fill(40, GY, 42, GY, '.');      // 挖掉地表行
b.fill(40, 14, 42, 14, 'X');      // 保留坑底 → 安全练习
b.coins(40, 42, 12);              // 坑里放金币：掉下去也有奖励，不是惩罚
/* 坑 B：几乎一样宽，但没有底 → 用刚学会的技巧真正跨越 */
b.fill(48, GY, 50, 14, '.');      // 真坑（3 格宽，走路跳可过）
b.ground(51, 77, GY);

/* —— 承：组合已学元素 —— */
/* 砖块 + 问号 + 双栗宝宝：撞块可以震死块上的敌人（进阶技巧，可发现） */
b.row(56, 60, 9, 'B');
b.block(58, 9, '?');
b.enemy('goomba', 57, 12);
b.enemy('goomba', 59, 12);

/* 教学 5：管道与食人花——踩不了的敌人（贴近管口它不出头 = 仁慈规则） */
b.pipe(64, 11);
b.enemy('piranha', 64, 11);
/* 第二根管道可进入 → 地下奖励室（奖励好奇心） */
b.pipe(70, 10, null, { area: 1, x: 2, y: 3 });
b.enemy('piranha', 70, 10);

/* 慢慢龟登场：踩一脚变壳、再碰会滑出——两步交互，排在栗宝宝之后教 */
b.enemy('koopa', 76, 12);

/* —— 转：垂直选择层 —— */
b.ground(78, 105, GY);
/* 单向木平台：从下面穿过去、从上面走——镂空侧面是"可穿过"的形式信号 */
b.row(82, 86, 9, '=');
b.coins(83, 85, 7);
b.row(89, 93, 6, '=');
b.coins(90, 92, 4);
b.enemy('goomba', 88, 12);
b.enemy('goomba', 91, 12);

/* 隐藏块（奖励好奇心：玩家在平台间跳跃时可能撞到） */
b.block(95, 8, 'h');
b.block(98, 6, '!');   // 隐藏 1UP：更高更难撞到

/* 白块秘密：蹲 1 秒落入背景层（"总会有人停下来看"） */
b.row(100, 102, 10, 'W');
b.block(101, 12, '"');

/* —— 合：P 速度跑道 + 飞行奖励 —— */
/* 30 格无障碍直路：地形本身在说"跑起来！"（用地形表现意图） */
b.ground(106, 149, GY);
b.coins(112, 138, 12);            // 贴地金币串引导全速冲刺
b.block(120, 9, '*');             // 无敌星：全速跑的路上顺手撞出，爽上加爽
/* 云上金币走廊：只有狸猫满 P 表起飞才吃得到（二周目的理由） */
b.row(128, 136, 3, 'c');
b.coins(128, 136, 2);
b.enemy('paratroopaRed', 142, 8); // 空中巡逻兵：跑道尽头的小考验

/* 终点前台阶：给冲刺一个腾空的跳台 */
b.stairsUp(150, 12, 4);
b.fill(154, GY, 156, 14, '.');    // 台阶后 3 格空隙：全速飞跃的高光时刻
b.ground(157, W - 1, GY);

/* 终点卡片（分析文档 §7：把通关变成一次小抽卡） */
b.block(163, 12, 'G');
b.block(163, 11, 'G');
b.goal(163, 8);

const main = b.toArea({ theme: 'overworld', music: 'overworld' });

/* —— 地下奖励室（经管道进入）—— */
const u = new LevelBuilder(24, 15);
u.fill(0, 0, 23, 0, 'X');               // 顶
u.ground(0, 23, 12);                     // 地
u.fill(0, 1, 0, 12, 'X');                // 左墙
u.fill(23, 1, 23, 12, 'X');              // 右墙
/* 金字塔金币阵 */
u.coins(6, 16, 10);
u.coins(8, 14, 8);
u.coins(10, 12, 6);
u.row(8, 14, 11, 'B');
u.block(11, 11, 'M');
/* 出口管道 → 回到地面管道后方（比进入点更远：地下是捷径） */
u.pipe(19, 10, 3, { area: 0, x: 74, y: 10 });
const bonus = u.toArea({ theme: 'underground', music: 'underground' });

export default {
  id: '1-1',
  name: 'GRASS LAND 1',
  time: 300,
  start: { area: 0, x: 3, y: GY },
  areas: [main, bonus]
};
